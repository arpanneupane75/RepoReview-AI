from app.models import CodeReview


def generate_markdown_report(review: CodeReview) -> str:
    lines = []

    lines.append(f"# Code Review: {review.repository}")
    lines.append("")

    lines.append("## Summary")
    lines.append("")
    lines.append(review.summary)
    lines.append("")

    lines.append("## Strengths")
    lines.append("")

    if review.strengths:
        for strength in review.strengths:
            lines.append(f"- {strength}")
    else:
        lines.append("- None identified")

    lines.append("")

    lines.append("## Code Quality Findings")
    lines.append("")

    if review.quality_findings:
        for index, finding in enumerate(
            review.quality_findings,
            start=1,
        ):
            lines.append(f"### {index}. {finding.title}")
            lines.append("")
            lines.append(f"**Severity:** {finding.severity}")
            lines.append("")

            if finding.file:
                location = finding.file

                if finding.line is not None:
                    location += f":{finding.line}"

                lines.append(f"**Location:** `{location}`")
                lines.append("")

            lines.append(f"**Description:** {finding.description}")
            lines.append("")
            lines.append(
                f"**Recommendation:** {finding.recommendation}"
            )
            lines.append("")
    else:
        lines.append("No code quality issues identified.")
        lines.append("")

    lines.append("## Security & Bug Findings")
    lines.append("")

    if review.security_findings:
        for index, finding in enumerate(
            review.security_findings,
            start=1,
        ):
            lines.append(f"### {index}. {finding.title}")
            lines.append("")
            lines.append(f"**Severity:** {finding.severity}")
            lines.append("")

            if finding.file:
                location = finding.file

                if finding.line is not None:
                    location += f":{finding.line}"

                lines.append(f"**Location:** `{location}`")
                lines.append("")

            lines.append(f"**Description:** {finding.description}")
            lines.append("")
            lines.append(
                f"**Recommendation:** {finding.recommendation}"
            )
            lines.append("")
    else:
        lines.append("No security or bug issues identified.")
        lines.append("")

    lines.append("## Recommendations")
    lines.append("")

    if review.recommendations:
        for recommendation in review.recommendations:
            lines.append(f"- {recommendation}")
    else:
        lines.append("- None")

    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(
        "Generated by RepoReview AI."
    )

    return "\n".join(lines)